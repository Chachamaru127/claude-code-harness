#!/usr/bin/env bash
# gen-tlds.sh — regenerate go/internal/runtimefloor/tlds.go from the IANA root zone.
#
# Usage:
#   cd go && bash scripts/gen-tlds.sh
#
# The schemeless-host check has to tell a host from a filename, and the final
# label is what separates them: notes.txt and config.json end in labels that
# are not TLDs, while evil.sh ends in a real ccTLD. The IANA list is the
# authoritative source and it does move — new TLDs are delegated and retired
# ones are removed — so re-run this and commit the result when it does. The
# checked-in copy is what ships; nothing fetches at runtime.
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
GO_DIR="$(cd "${SCRIPT_DIR}/.." && pwd)"
OUT="${GO_DIR}/internal/runtimefloor/tlds.go"
URL="https://data.iana.org/TLD/tlds-alpha-by-domain.txt"

tmp="$(mktemp "${TMPDIR:-/tmp}/tlds.XXXXXX")"
trap 'rm -f "$tmp"' EXIT

curl -fsS --max-time 60 "$URL" -o "$tmp"

version="$(awk '/^# Version/ {v=$3; gsub(/,/, "", v); print v; exit}' "$tmp")"

{
  printf '// Code generated by go/scripts/gen-tlds.sh. DO NOT EDIT.\n\n'
  printf 'package runtimefloor\n\n'
  printf '// registeredTLDs is the set of top-level domains in the IANA root zone.\n'
  printf '// It exists so the schemeless-host check can tell a host from an ordinary\n'
  printf '// filename: notes.txt and config.json do not end in a registered TLD, while\n'
  printf '// evil.sh and example.dev do. Source list version: %s.\n' "${version:-unknown}"
  printf 'var registeredTLDs = map[string]struct{}{\n'
  awk '!/^#/ && NF {print tolower($0)}' "$tmp" \
    | LC_ALL=C sort -u \
    | grep -E '^[a-z0-9-]{2,63}$' \
    | awk '{ if (n % 8 == 0) { if (n > 0) printf "\n"; printf "\t" } else { printf " " } printf "\"%s\": {},", $0; n++ } END { if (n > 0) printf "\n" }'
  printf '}\n'
} > "$OUT"

echo "wrote ${OUT} (source list version: ${version:-unknown})"
